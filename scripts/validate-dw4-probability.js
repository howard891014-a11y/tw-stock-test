'use strict';
const assert=require('assert');
const fs=require('fs');
const D=require('../lib/dw4');
const {fitSignCalibration,directionProbability}=require('../lib/dw4-probability');
assert.strictEqual(D.regime('RiskOn'),1);
assert.strictEqual(D.regime('Normal'),0);
assert.strictEqual(D.regime('RiskOff'),-1);
assert.strictEqual(D.regime('2026-07-31'),null,'no frozen date-defined W3 state');
assert.strictEqual(D.regime(undefined),null);
const sample=[];
for(let i=0;i<100;i++)sample.push({date:`2026-08-${String(1+(i%25)).padStart(2,'0')}`,pred:(i%11-5)*.45,real:(i%11-5)*.6+(i%4===0?-1:1)});
assert(!fitSignCalibration(sample.slice(0,10),5).available);
const cal=fitSignCalibration(sample,5);
assert(cal.available&&cal.distinctDates===25);
const a=directionProbability(cal,1.3),b=directionProbability(cal,-1.3);
assert(Number.isFinite(a.upProbability));
assert(a.upProbability>=b.upProbability,'higher predicted price return must not reduce up probability');
assert(Math.abs(b.directionProbability-(100-b.upProbability))<.11);
assert.equal(directionProbability({available:false,status:'insufficient'},4).directionProbability,null);
assert.equal(directionProbability(cal,NaN).directionProbability,null);
const prices=Array.from({length:11},(_,i)=>({return_1_pct:i%3===0?-1.0:2.0}));
const f=D.priceMomentumAndVol(prices,10);
assert(f.dy3_turn!==null&&f.vol_10>0);
assert(D.Y_FEATURES.includes('dy3_turn')&&D.Y_FEATURES.includes('vol_10'));
assert(D.Y_FEATURES.includes('flow_5_pct')&&D.Y_FEATURES.includes('x_score'));
assert(D.Y_FEATURES.includes('regime'));
let aWithMissing=prices.map(r=>({...r}));aWithMissing[4].return_1_pct=null;
assert.equal(D.priceMomentumAndVol(aWithMissing,10).dy3_turn,null,'missing return never treated as zero');
const historic=Array.from({length:48},(_,i)=>({trade_date:new Date(Date.UTC(2026,5,i+1)).toISOString().slice(0,10),tag_id:'mcu',x_score:i/4,y_score:i/3,flow_1_pct:i%5-2,flow_5_pct:1,return_1_pct:.3}));
const feats=D.featuresAt(historic,47,5,new Map([[historic[47].trade_date,'RiskOff']]));
assert.strictEqual(feats.regime,-1);
assert.strictEqual(D.featuresAt(historic,47,5).regime,null);
const app=fs.readFileSync('app.js','utf8');const html=fs.readFileSync('index.html','utf8');
assert(app.includes('fundflowDirectionProbabilityLabel(p,true)'));
assert(app.includes('confidenceStatus:prediction.confidenceStatus'));
assert(html.includes('fundflow-return-prob'));
console.log('dW4 sign probability / W3 dynamic / UI mapping regression PASS');
