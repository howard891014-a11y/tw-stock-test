const assert=require('assert');
const fs=require('fs');
const {summarizeDw4Audit}=require('../lib/dw4-audit');
const {DIRECTIONS,DW4_VERSION}=require('../lib/dw4');
const active=Array.from({length:12},(_,i)=>({tag_id:'sector'+i,members:i===11?1:5}));
const makePred=(h,i)=>({tagId:'sector'+i,predDx:i+1,predDy:i*.01,direction:DIRECTIONS[0],horizon:h,predictionDate:'2026-10-08'});
const res={ok:true,modelVersion:DW4_VERSION,predictionDate:'2026-10-08',horizonResults:Object.fromEntries([5,10,15,20].map(h=>[h,{ok:true,training:{x:500,y:500},predictions:Array.from({length:11},(_,i)=>makePred(h,i))}]))};
const pass=summarizeDw4Audit(res,active,'2026-10-08');
assert(pass.ok);assert(pass.dateAligned);assert(pass.readOnly);assert.strictEqual(pass.eligibleTags,11);
assert([5,10,15,20].every(h=>pass.horizonResults[h].validEligible===11&&pass.horizonResults[h].coveragePct===100));
assert(!summarizeDw4Audit(res,active,'2026-10-07').ok,'stale XY/dW4 dates must fail');
const broken=JSON.parse(JSON.stringify(res));broken.horizonResults[10].predictions[0].predDx=null;
assert(!summarizeDw4Audit(broken,active,'2026-10-08').ok,'invalid predicted delta must fail');
const sparse=JSON.parse(JSON.stringify(res));sparse.horizonResults[15].predictions=sparse.horizonResults[15].predictions.slice(0,4);
assert(!summarizeDw4Audit(sparse,active,'2026-10-08').ok,'low coverage must fail');
const withOld=JSON.parse(JSON.stringify(res));withOld.horizonResults[5].predictions.push({...makePred(5,0),tagId:'retired_mother'});
assert(summarizeDw4Audit(withOld,active,'2026-10-08').ok,'unmatched history tags are reported, never treated as eligible');
assert.equal(summarizeDw4Audit(withOld,active,'2026-10-08').horizonResults[5].unmatchedHistoryTags,1);
const app=fs.readFileSync('app.js','utf8'),html=fs.readFileSync('index.html','utf8'),core=fs.readFileSync('lib/fundflow-xy.js','utf8'),api=fs.readFileSync('api/dw4.js','utf8');
assert(html.includes('執行 XY／dW4 驗證')&&!html.includes('執行 XY / Path 驗證'));
assert(app.includes('/api/dw4?view=audit')&&app.includes('fundflow-audit&target=60'));
assert(!app.includes('Path 5D Top1')&&!app.includes('Path audit 重建逾時'));
assert(!core.includes('pathTop1AtLeast60:Boolean(path.target60Reached)'));
assert(api.includes('persist:false')&&api.includes('view===\'audit\''));
console.log('StockZone v2.6.7.5 dW4/XY acceptance tests PASS');
