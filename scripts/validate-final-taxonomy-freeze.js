assert(copos.every(([,pairs])=>pairs.find(([id])=>id==='copos')[1]==='related'),'CoPoS must be related supply-chain exposure');
for(const code of ['1516','3054','4564','6538','8932','9950'])assert.deepEqual(freeze.companyTopicPairs(code),[],`${code} must remain strict no-tag`);
for(const retired of ['lead_material_recycling','nand','semiconductor_products_services','pi_film','smart_meter_energy_management','holographic_optical_material','thin_client','special_metal','electronic_components_manufacturing'])assert(!freeze.definitionById(retired),`${retired} must not be in final 203`);
for(const added of ['shipbuilding','optical_storage','display_panel','compound_semiconductor','cof_substrate','environmental_recycling','hand_tools','fastener','beauty_care','protection_component'])assert(freeze.definitionById(added),`${added} final tag missing`);
assert.equal(tax.version,'2.3.1-final203');
assert.equal(xy.ENGINE_VERSION,'xy-8.4.4-clean-feature2-path311-taxonomy26');
assert.equal(xy.SNAPSHOT_SCHEMA_VERSION,'snapshot-7.0.4-focuspack-path31-taxonomy26-browser203');
assert(status.includes("action==='taxonomy-sync-export-manual'"));
assert(status.includes('syncFinalTaxonomyAndBuildDiagnostic'));
assert(app.includes('manualTaxonomySyncExport'));
assert(app.includes('downloadTaxonomyDiagnostic'));
const core=require('node:fs').readFileSync(require.resolve('../lib/fundflow-xy'),'utf8');
assert(core.includes('m.importance IS DISTINCT FROM EXCLUDED.importance'),'member sync must skip unchanged rows');
assert(core.includes('m.stock_code = ANY($2::text[])'),'manual taxonomy sync must scope deletes to frozen company universe');
assert.deepEqual(freeze.RETIRED_COMPANY_CODES,['8183','6806']);
assert.deepEqual(freeze.companyTopicPairs('8183'),[],'8183 delisted company must not remain in active Company_Map');
assert(core.includes('managedCodes=[...new Set([...frozenCodes,...retiredCodes])]'),'retired codes must be included in cleanup scope');
for(const t of ['shipping','oil_gas_utility','ccl','bbu','semiconductor_test_equipment_market'])assert(!freeze.definitionById(t),`${t} impure parent must be removed`);
assert.deepEqual(freeze.companyTopicPairs('6806'),[],'6806 must stay retired');
assert.equal(freeze.companyTopicPairs('2603').some(p=>p[0]==='shipping_container'),true);
assert.equal(freeze.companyTopicPairs('2633').some(p=>p[0]==='shipping_rail'),true);
assert.equal(freeze.listDefinitions().filter(d=>d.companyCount<3).length,13);
console.log('PASS validate-final-taxonomy-freeze — 203 tags / 3440 active edges / retired-code cleanup');
