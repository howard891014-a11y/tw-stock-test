'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const app=fs.readFileSync(path.join(root,'app.js'),'utf8');
const labSource=fs.readFileSync(path.join(root,'lib/resonance-lab-v1.js'),'utf8');
const tradeSource=fs.readFileSync(path.join(root,'lib/trade-orchestrator-v4.js'),'utf8');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const lab=require('../lib/resonance-lab-v1.js');
const trade=require('../lib/trade-orchestrator-v4.js');
const strategies=lab.STRATEGIES;
const make=(key,count,avg,median,win,mae)=>({strategy:strategies.find(s=>s.key===key),stats:{count,avgPct:avg,medianPct:median,winPct:win,avgMaePct:mae}});
const report={valid:true,results:[make('short',18,1,0.3,55,-5),make('mixed',18,2,0.4,58,-6),make('swing',18,2.88,1.5,61.1,-6.65),make('long-swing',18,2,0.7,56,-12),make('long',18,-2,-1,45,-18)]};
assert.equal(lab.selectFiveYearPlay(report)?.key,'swing','R1 selects qualifying best efficiency');
assert.equal(lab.selectFiveYearPlay(report)?.stats?.winPct,61.1);
assert.equal(lab.selectFiveYearPlay({valid:true,results:report.results.map(r=>({...r,stats:{...r.stats,medianPct:-1}}))})?.key,null,'No hidden V4 fallback when none eligible');
assert.equal(lab.selectFiveYearPlay({valid:false,results:report.results}),null);
const bars=[];
for(let i=0;i<1260;i++){
 const date=new Date(Date.UTC(2021,0,4+i)).toISOString().slice(0,10),close=100*Math.pow(1.00042,i),open=close*.999;
 bars.push({date,open,high:close*1.012,low:close*.988,close});
}
const full=lab.backtestPriceBaselines(bars,{warmup:120,stride:60,costPct:.5});
assert(full.valid);assert.equal(full.assumptions.stride,60);
assert.equal(full.coverage.signals,19,'The actual 1260-bar window and original 60-day stride yield 19 signals');
assert.equal(full.results.length,5);
assert(!labSource.includes('band[fixedKey]'),'Core allocation independent of locked play bands');
assert(!tradeSource.includes('band[fixedKey]'),'Core allocation cannot be clamped by play');
const holding=trade.splitPosition({available:true,key:'swing',basePct:65,tacticalPct:35},
 {shares:100,lockedPlayKey:'short'},100);
assert(holding.valid);assert.equal(holding.basePct,65);assert.equal(holding.tacticalPct,35);
assert.equal(holding.styleKey,'short','Prior play key is locked without clamping independent allocation');
assert(holding.holdingLock?.verified);
const context={valid:true,price:130,ma20:120,ma60:110,ma120:100,ret20Pct:10,volatilityPct:2};
const coreShort=lab.proposeAllocation({play:'short',baseCorePct:65,context,market:'on'});
const coreLong=lab.proposeAllocation({play:'long-swing',baseCorePct:65,context,market:'on'});
assert(coreShort.valid&&coreLong.valid);
assert.equal(coreShort.corePct,70,'Dynamic allocation not clipped by short play band');
assert.equal(coreShort.corePct,coreLong.corePct,'On-market allocation independent of five-year strategy');
assert.equal(lab.proposeAllocation({play:'short',baseCorePct:65,context,market:'off'}).corePct,0,'Existing W3 off short exit remains unchanged');
assert.equal(lab.proposeAllocation({play:'long-swing',baseCorePct:65,context,market:'off'}).tacticalPct,0,'Existing W3 off long-swing tactical exit remains unchanged');
assert(app.includes('syncFiveYearDisplay();')&&app.includes('fiveYearRecommendation()'),'Formal label uses R1');
assert(labSource.includes('coreExitPolicy:coreStrategy?{maxTradingDays:coreStrategy.days')&&labSource.includes('coreStrategy.stopPct'),'Core exit policy is derived only from R1 fixed strategy');
assert(labSource.includes('getCurrentFiveYearPlay')&&labSource.includes('stockzone:five-year-play'),'R1 result is stock-scoped and observable');
assert(labSource.includes('機動倉：${r.trial.stopTiming}')&&labSource.includes('機動倉：${r.trial.replenishTiming}'),'Recent held signals are tactical only');
assert(labSource.includes('既有交易計畫：')&&labSource.includes('保持原始鎖定'),'Plan remains locked and distinct from fresh recommendation');
assert(html.includes('v2.7.0.9')&&html.includes('app.js?v=2.7.0.9')&&html.includes('trade-orchestrator-v4.js?v=2.7.0.9'),'Version and asset invalidation');
assert.equal(require('../package.json').version,'2.7.0.9');
console.log('PASS v2.7.0.9: R1 recommendation, 60D stride, no-qualified, independent allocation, locked plans, tactical-only recent, cache/version');
